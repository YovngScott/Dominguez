begin;

-- Los dos recorridos comparten el punto de corte inicial. La llegada de
-- correos nuevos no cambia la consulta paginada del historial.
create table public.correo_recorridos (
  cuenta uuid not null references public.asistente_correo_cuentas on delete cascade,
  tipo text not null check (tipo in ('historico','reciente')),
  desde bigint not null,
  hasta bigint not null,
  pagina text not null default '',
  terminado boolean not null default false,
  version integer not null default 0,
  error text,
  primary key (cuenta,tipo)
);

-- Una fila para el mensaje y otra por PDF. El resultado manual se conserva
-- cuando Gmail devuelve de nuevo un mensaje dentro del solapamiento.
create table public.correo_indice (
  id bigint generated by default as identity primary key,
  cuenta uuid not null references public.asistente_correo_cuentas on delete cascade,
  gmail_id text not null,
  parte text not null default 'correo',
  historico boolean not null,
  hilo text, asunto text, remitente text, fecha timestamptz, archivo text, aseguradora text,
  chasis text[] not null default '{}',
  evidencia jsonb not null default '[]',
  orden boolean not null default false,
  estado text not null default 'pendiente' check (estado in ('pendiente','listo','incidencia')),
  detalle text, revisado timestamptz,
  intentos integer not null default 0,
  disponible timestamptz not null default now(),
  turno uuid,
  unique (cuenta,gmail_id,parte)
);
create index correo_indice_chasis on public.correo_indice using gin(chasis);
create index correo_indice_pendientes on public.correo_indice(disponible,id) where estado='pendiente';
create index correo_indice_revision on public.correo_indice(fecha desc,id) where revisado is null and (orden or estado='incidencia');
create index correo_indice_cobertura on public.correo_indice(cuenta,historico,estado);

alter table public.correo_recorridos enable row level security;
alter table public.correo_indice enable row level security;
revoke all on public.correo_recorridos, public.correo_indice from public, anon, authenticated;
grant all on public.correo_recorridos, public.correo_indice to service_role;
grant usage, select on sequence public.correo_indice_id_seq to service_role;

create function public.correo_tomar_lote(cantidad integer, llave uuid)
returns setof public.correo_indice language sql security invoker set search_path='' as $$
  with proximos as (
    select i.id from public.correo_indice i
    join public.asistente_correo_cuentas c on c.id=i.cuenta and c.activa
    where i.estado='pendiente' and i.disponible<=now()
    order by i.historico, i.disponible, i.id
    limit least(greatest(cantidad,1),24) for update of i skip locked
  )
  update public.correo_indice i
  set turno=llave, disponible=now()+interval '5 minutes', intentos=intentos+1
  from proximos where i.id=proximos.id returning i.*;
$$;
revoke all on function public.correo_tomar_lote(integer,uuid) from public, anon, authenticated;
grant execute on function public.correo_tomar_lote(integer,uuid) to service_role;

create view public.correo_cobertura with (security_invoker=true) as
  select c.id,c.email,h.desde,h.hasta,h.terminado,h.error as error_historico,
    r.desde as actualizado,r.error as error_reciente,
    count(i.id) filter (where i.estado='pendiente' and i.historico) as pendientes_historicos,
    count(i.id) filter (where i.estado='incidencia' and i.historico and i.revisado is null) as incidencias_historicas_abiertas,
    count(i.id) filter (where i.estado='pendiente') as pendientes,
    count(i.id) filter (where i.estado='incidencia') as incidencias,
    count(i.id) filter (where i.parte='correo' and i.estado='listo') as correos,
    count(i.id) filter (where i.parte<>'correo' and i.estado='listo') as pdf
  from public.asistente_correo_cuentas c
  left join public.correo_recorridos h on h.cuenta=c.id and h.tipo='historico'
  left join public.correo_recorridos r on r.cuenta=c.id and r.tipo='reciente'
  left join public.correo_indice i on i.cuenta=c.id
  where c.activa group by c.id,h.cuenta,h.tipo,r.cuenta,r.tipo;
revoke all on public.correo_cobertura from public, anon, authenticated;
grant select on public.correo_cobertura to service_role;

